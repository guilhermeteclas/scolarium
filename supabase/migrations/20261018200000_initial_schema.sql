-- ============================================
-- SCHEMA INICIAL - Scolarium
-- ============================================
-- Inferido do código-fonte (src/types/*) e supabase/policies.sql (antigo)
-- Papéis: admin (total), manager (seus inventários/itens, todos os pedidos),
--         user (apenas seus pedidos)
-- ============================================

-- ============================================
-- PROFILES
-- ============================================
-- Espelha auth.users; papel (role) controla RLS e permissões do frontend
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  first_name text,
  last_name text,
  role text not null default 'user' check (role in ('admin', 'manager', 'user'))
);

comment on table public.profiles is 'Perfis de usuário; id referencia auth.users';

-- ============================================
-- INVENTORIES
-- ============================================
create table public.inventories (
  id bigint generated by default as identity primary key,
  name text not null,
  description text
);

comment on table public.inventories is 'Almoxarifados e espaços de armazenamento';

-- ============================================
-- USER_INVENTORIES (associação manager/inventário)
-- ============================================
create table public.user_inventories (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles (id) on delete cascade,
  inventory_id bigint not null references public.inventories (id) on delete cascade,
  unique (profile_id, inventory_id)
);

comment on table public.user_inventories is 'Vincula managers aos inventários que administram';

-- ============================================
-- ITEMS
-- ============================================
create table public.items (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null check (type in ('material', 'service', 'equipment')),
  quantity integer not null default 0 check (quantity >= 0),
  inventory_id bigint not null references public.inventories (id) on delete cascade
);

comment on table public.items is 'Itens do almoxarifado (materiais, serviços, equipamentos)';

-- ============================================
-- REQUESTS (pedidos/requisições)
-- ============================================
create table public.requests (
  id bigint generated by default as identity primary key,
  details text,
  reservation_start timestamptz not null,
  reservation_end timestamptz not null,
  status text not null default 'open'
    check (status in ('open', 'in_progress', 'pending', 'ready', 'completed', 'rejected', 'cancelled')),
  profile_id uuid not null references public.profiles (id) on delete cascade,
  date timestamptz not null default now(),
  check (reservation_end >= reservation_start)
);

comment on table public.requests is 'Pedidos/requisições de materiais com período de reserva';

-- ============================================
-- REQUEST_ITEMS (itens do pedido)
-- ============================================
create table public.request_items (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.requests (id) on delete cascade,
  item_id bigint not null references public.items (id) on delete cascade,
  quantity integer not null check (quantity > 0),
  checked_out integer not null default 0 check (checked_out >= 0),
  returned integer not null default 0 check (returned >= 0),
  unique (request_id, item_id),
  check (returned <= checked_out)
);

comment on table public.request_items is 'Itens solicitados por pedido, com retiradas e devoluções';

-- ============================================
-- ÍNDICES (acessos frequentes via RLS e queries do app)
-- ============================================
create index idx_user_inventories_profile_id on public.user_inventories (profile_id);
create index idx_user_inventories_inventory_id on public.user_inventories (inventory_id);
create index idx_items_inventory_id on public.items (inventory_id);
create index idx_requests_profile_id on public.requests (profile_id);
create index idx_requests_status on public.requests (status);
create index idx_request_items_request_id on public.request_items (request_id);
create index idx_request_items_item_id on public.request_items (item_id);

-- ============================================
-- TRIGGER: cria profile automaticamente no signup
-- ============================================
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, first_name, last_name, role)
  values (
    new.id,
    new.raw_user_meta_data ->> 'first_name',
    new.raw_user_meta_data ->> 'last_name',
    coalesce(new.raw_user_meta_data ->> 'role', 'user')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
